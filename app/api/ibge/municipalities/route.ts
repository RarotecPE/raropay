export async function GET(request: NextRequest) {
  const state = request.nextUrl.searchParams.get('state')
  
  if (!state) {
    return NextResponse.json({ error: 'Estado é obrigatório' }, { status: 400 })
  }

  try {
    // Tentar buscar da API do IBGE com timeout
    const controller = new AbortController()
    const timeoutId = setTimeout(() => controller.abort(), 5000) // 5 segundos de timeout
    
    const response = await fetch(
      `https://servicodados.ibge.gov.br/api/v1/localidades/estados/${state}/municipios?orderBy=nome`,
      { 
        signal: controller.signal,
        next: { revalidate: 86400 } // Cache por 24 horas
      }
    )
    
    clearTimeout(timeoutId)

    if (!response.ok) {
      throw new Error('Erro ao buscar municípios')
    }

    const data = await response.json()
    
    const municipalities = data.map((m: { id: number; nome: string }) => ({
      id: m.id,
      name: m.nome,
    }))

    return NextResponse.json(municipalities)
  } catch (error) {
    console.error('Erro ao buscar municípios da API do IBGE, usando fallback:', error)
    
    // Usar fallback local se disponível
    const fallback = MUNICIPALITIES_FALLBACK[state.toUpperCase()]
    if (fallback) {
      return NextResponse.json(fallback)
    }
    
    return NextResponse.json(
      { error: 'Erro ao buscar municípios' },
      { status: 500 }
    )
  }
}
